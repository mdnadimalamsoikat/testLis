-- ===========================================================================
-- LIS Middleware — APEX control layer (Oracle 19c)
--
-- Run once, as the LIS schema user (the same user the middleware connects as):
--     sqlplus lis_user/password@//192.168.1.100:1521/ORCL @database/apex_install.sql
-- (SQL Developer: open this file, Run Script — F5.)
--
-- After this, the middleware is driven entirely from APEX:
--   * lis_config        one row per analyzer + one row per setting
--   * lis_test_code_map machine code → report code
--   * lis_commands      APEX buttons → commands the service executes
--   * lis_analyzer_status  heartbeat the service writes back
--   * v_* views         what the APEX pages select from
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. configuration (APEX form edits these rows)
-- ---------------------------------------------------------------------------
CREATE TABLE lis_config (
    config_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_type      VARCHAR2(20)  DEFAULT 'ANALYZER' NOT NULL,  -- ANALYZER | SETTING
    analyzer_name    VARCHAR2(100),
    display_order    NUMBER DEFAULT 10,
    enabled          CHAR(1)  DEFAULT 'Y' NOT NULL,
    status           VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,      -- ACTIVE | DRAFT
    protocol         VARCHAR2(10),                                -- ASTM | HL7 | AUTO
    connection_type  VARCHAR2(10),                                -- TCP | SERIAL
    host             VARCHAR2(120) DEFAULT '0.0.0.0',
    port             NUMBER,
    serial_port      VARCHAR2(40),
    baud_rate        NUMBER DEFAULT 9600,
    data_bits        NUMBER DEFAULT 8,
    parity           VARCHAR2(10) DEFAULT 'NONE',
    stop_bits        NUMBER DEFAULT 1,
    brand            VARCHAR2(60),
    model            VARCHAR2(60),
    test_codes       VARCHAR2(500),             -- comma list: WBC,RBC,HGB
    test_code_map    VARCHAR2(1000),            -- JSON: {"HGB":"HB"}
    config_key       VARCHAR2(60),              -- for config_type = SETTING
    config_value     VARCHAR2(500),
    note             VARCHAR2(500),
    -- bookkeeping written by the service
    config_version   NUMBER DEFAULT 1 NOT NULL,
    applied_at       TIMESTAMP,
    last_applied_at  TIMESTAMP,
    applied_by       VARCHAR2(100),
    last_error       VARCHAR2(500),
    last_error_at    TIMESTAMP,
    updated_by       VARCHAR2(100) DEFAULT SYS_CONTEXT('USERENV', 'OS_USER'),
    updated_at       TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX idx_lis_config_type ON lis_config (config_type, status);
-- unique per (type, name) — a config_key ALSO lives in analyzer_name for
-- SETTING rows, so a plain UNIQUE(analyzer_name) would block the second setting
CREATE UNIQUE INDEX uq_lis_config_name ON lis_config (config_type, analyzer_name);
CREATE INDEX idx_lis_config_key ON lis_config (config_key);

-- ---------------------------------------------------------------------------
-- 2. machine code → report code
-- ---------------------------------------------------------------------------
CREATE TABLE lis_test_code_map (
    map_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code VARCHAR2(30) NOT NULL,
    lis_code     VARCHAR2(30) NOT NULL,
    analyzer_name VARCHAR2(100),          -- NULL = applies to every analyzer
    status       VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    note         VARCHAR2(200),
    updated_at   TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE UNIQUE INDEX uq_code_map ON lis_test_code_map
    (machine_code, NVL(analyzer_name, '*'));

-- ---------------------------------------------------------------------------
-- 3. command queue (APEX buttons)
-- ---------------------------------------------------------------------------
CREATE TABLE lis_commands (
    command_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_type   VARCHAR2(20) NOT NULL,      -- RELOAD|START|STOP|RESTART|SELFTEST|PING
    analyzer_name  VARCHAR2(100),
    payload        VARCHAR2(200),              -- e.g. scenario name for SELFTEST
    status         VARCHAR2(12) DEFAULT 'PENDING' NOT NULL,  -- PENDING|RUNNING|DONE|FAILED
    requested_by   VARCHAR2(100) DEFAULT SYS_CONTEXT('USERENV', 'OS_USER'),
    requested_at   TIMESTAMP DEFAULT SYSTIMESTAMP,
    started_at     TIMESTAMP,
    finished_at    TIMESTAMP,
    result_message VARCHAR2(1000)
);

CREATE INDEX idx_lis_commands_pending ON lis_commands (status, requested_at);

-- ---------------------------------------------------------------------------
-- 4. heartbeat — lis_analyzer_status already exists (database/schema.sql);
--    here we only add the columns the control plane wants.
-- ---------------------------------------------------------------------------
-- Conditional and re-runnable: a plain ADD raises ORA-01430 when the column
-- already exists (newer schema.sql, or a second run of this script). Because
-- v_lis_analyzers below selects these columns, "already there" is FINE — but
-- "partially there" would break the view, hence one check per column.
DECLARE
    PROCEDURE add_col(p_name VARCHAR2, p_type VARCHAR2) IS
        n NUMBER;
    BEGIN
        SELECT COUNT(*) INTO n FROM user_tab_columns
         WHERE table_name = 'LIS_ANALYZER_STATUS' AND column_name = p_name;
        IF n = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE lis_analyzer_status ADD (' || p_name || ' ' || p_type || ')';
        END IF;
    END;
BEGIN
    add_col('HOST',               'VARCHAR2(120)');
    add_col('PORT',               'NUMBER');
    add_col('ACTIVE_CONNECTIONS', 'NUMBER DEFAULT 0');
    add_col('MESSAGES_RECEIVED',  'NUMBER DEFAULT 0');
    add_col('LAST_MESSAGE_AT',    'TIMESTAMP');
END;
/

