-- ---------------------------------------------------------------------------
-- LIS Middleware schema — Oracle 19c / 21c / 23ai (12c+ compatible)
-- Run as the LIS schema user:  sqlplus lis_user/password @schema.sql
-- ---------------------------------------------------------------------------

-- 1. Raw messages: every payload exactly as the analyzer sent it.
--    Never delete from here — it is the replay/debug source of truth.
CREATE TABLE lis_raw_messages (
    message_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analyzer_name VARCHAR2(100)  NOT NULL,
    protocol      VARCHAR2(10),
    peer          VARCHAR2(100),
    raw_message   CLOB,
    received_at   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    processed_at  TIMESTAMP,
    status        VARCHAR2(20)   DEFAULT 'RECEIVED' NOT NULL,
    note          VARCHAR2(500)
);

CREATE INDEX idx_raw_received ON lis_raw_messages (received_at DESC);
CREATE INDEX idx_raw_status   ON lis_raw_messages (status);

-- 2. One row per test result. The unique key makes re-transmissions safe.
CREATE TABLE lab_results (
    result_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id       VARCHAR2(50)   NOT NULL,
    patient_id      VARCHAR2(50),
    patient_name    VARCHAR2(150),
    test_code       VARCHAR2(30)   NOT NULL,
    result_value    NUMBER,
    result_text     VARCHAR2(100),
    result_unit     VARCHAR2(30),
    ref_range       VARCHAR2(50),
    abnormal_flag   VARCHAR2(5)    DEFAULT 'N',
    is_abnormal     CHAR(1)        DEFAULT 'N',
    is_critical     CHAR(1)        DEFAULT 'N',
    analyzer_name   VARCHAR2(100)  NOT NULL,
    protocol        VARCHAR2(10),
    result_datetime TIMESTAMP,
    received_at     TIMESTAMP      DEFAULT SYSTIMESTAMP,
    raw_message     VARCHAR2(4000),
    CONSTRAINT uq_result UNIQUE (sample_id, test_code, analyzer_name, result_value)
);

CREATE INDEX idx_results_sample   ON lab_results (sample_id);
CREATE INDEX idx_results_received ON lab_results (received_at DESC);
CREATE INDEX idx_results_patient  ON lab_results (patient_id);
CREATE INDEX idx_results_critical ON lab_results (is_critical) ;

-- 3. Audit trail: who sent what, when, and what happened to it.
CREATE TABLE lis_audit_log (
    audit_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR2(50),
    analyzer_name VARCHAR2(100),
    detail        VARCHAR2(1000),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- 4. Analyzer heartbeat, useful on the APEX status page.
CREATE TABLE lis_analyzer_status (
    analyzer_name   VARCHAR2(100) PRIMARY KEY,
    protocol        VARCHAR2(10),
    connection_type VARCHAR2(20),
    last_seen_at    TIMESTAMP,
    messages_today  NUMBER DEFAULT 0,
    state           VARCHAR2(20) DEFAULT 'UNKNOWN'
);

-- ---------------------------------------------------------------------------
-- Views for Oracle APEX reports
-- ---------------------------------------------------------------------------

-- Report 1: results of one sample, ready for the "Result Entry" page
CREATE OR REPLACE VIEW v_sample_results AS
SELECT sample_id,
       MAX(patient_id)   AS patient_id,
       MAX(patient_name) AS patient_name,
       MAX(analyzer_name) AS analyzer_name,
       MAX(received_at)  AS received_at,
       COUNT(*)          AS test_count,
       SUM(CASE WHEN is_abnormal = 'Y' THEN 1 ELSE 0 END) AS abnormal_count
  FROM lab_results
 GROUP BY sample_id;

-- Report 2: newest results with a critical flag (auto-refresh dashboard)
CREATE OR REPLACE VIEW v_critical_results AS
SELECT result_id, sample_id, patient_name, test_code,
       result_value, result_text, ref_range, analyzer_name, received_at
  FROM lab_results
 WHERE is_critical = 'Y'
 ORDER BY received_at DESC;

-- Report 3: analyzer throughput per hour
CREATE OR REPLACE VIEW v_analyzer_throughput AS
SELECT analyzer_name,
       TO_CHAR(received_at, 'YYYY-MM-DD HH24') AS hour_bucket,
       COUNT(*) AS results
  FROM lab_results
 GROUP BY analyzer_name, TO_CHAR(received_at, 'YYYY-MM-DD HH24');

